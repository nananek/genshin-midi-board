def unique(values: list[float]) -> list[float]:
    out: list[float] = []
    for value in sorted(values):
        if not out or abs(value - out[-1]) > 0.001:
            out.append(value)
    return out


def pitch_of(*groups: list[float]) -> float:
    steps = [
        round(b - a, 4)
        for values in groups
        for a, b in zip(values, values[1:])
        if b - a > 0.001
    ]
    if not steps:
        return 0.0
    return Counter(steps).most_common(1)[0][0]


def footprint_name(fp: pcbnew.FOOTPRINT) -> str:
    fpid = fp.GetFPID()
    lib = fpid.GetLibNickname()
    item = fpid.GetLibItemName()
    return f"{lib}:{item}" if lib else item


def main() -> None:
    board = pcbnew.LoadBoard(str(PCB))
    rows: list[str] = []
    notes: list[str] = []

    for ref, expected in DATASHEET.items():
        fp = board.FindFootprintByReference(ref)
        if fp is None:
            rows.append(f"| {ref} | {expected['part']} | missing | - | - | - | - | - | MISSING |")
            notes.append(f"{ref}: footprint not found")
            continue

        pads = list(fp.Pads())
        xs = [TOMM(p.GetPosition().x) for p in pads]
        ys = [TOMM(p.GetPosition().y) for p in pads]
        ux = unique(xs)
        uy = unique(ys)
        row = max(max(xs) - min(xs), max(ys) - min(ys))
        pitch = pitch_of(ux, uy)

        pad1 = fp.FindPadByNumber("1")
        pad1_net = pad1.GetNetname() if pad1 else ""
        pad1_ok = pad1_net == expected["pin1"]
        row_ok = abs(row - expected["row"]) <= 0.1
        pitch_ok = abs(pitch - expected["pitch"]) <= 0.01
        pads_ok = len(pads) == expected["pads"]
        ok = pad1_ok and row_ok and pitch_ok and pads_ok

        verdict = "OK" if ok else "MISMATCH"
        rows.append(
            f"| {ref} | {expected['part']} | `{footprint_name(fp)}` | {len(pads)} | "
            f"{row:.2f} | {pitch:.2f} | {expected['package']} | "
            f"`{pad1_net}` | {verdict} |"
        )
        if not ok:
            reasons = []
            if not pads_ok:
                reasons.append(f"pad count {len(pads)} != {expected['pads']}")
            if not row_ok:
                reasons.append(f"pad row {row:.2f} != {expected['row']:.2f}")
            if not pitch_ok:
                reasons.append(f"pitch {pitch:.2f} != {expected['pitch']:.2f}")
            if not pad1_ok:
                reasons.append(f"pad1 net {pad1_net} != {expected['pin1']}")
            notes.append(f"{ref}: " + ", ".join(reasons))

    lines = [
        "# IC フットプリント照合",
        "",
        "Generated by `scripts/export_ic_footprints.py` from the routed board. "
        "Do not edit; run `make ic-footprints` to update.",
        "",
        "| Ref | 型番 | KiCad footprint | Pads | パッド列間 (mm) | ピッチ (mm) | データシート package | pad1 ネット | 判定 |",
        "| --- | --- | --- | ---: | ---: | ---: | --- | --- | --- |",
        *rows,
        "",
    ]
    if notes:
        lines.append("## 不一致")
        lines.append("")
        for note in notes:
            lines.append(f"- {note}")
        lines.append("")
    if any(note.startswith("U2:") for note in notes):
        lines.append(
            "U2 のフットプリントが W25Q128JVSIQ の 208-mil パッケージと一致していない。"
            "`SOIC-8_5.3x5.3mm_P1.27mm` を使う。"
        )
    elif notes:
        lines.append("上記の IC はデータシートのパッケージと一致していない。")
    else:
        lines.append("すべての IC のフットプリントがデータシートのパッケージと一致している。")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
